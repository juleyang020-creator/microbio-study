#!/usr/bin/env node
// 批43：GM 试验条目补强（EORTC/MSG 2020 界值 + BALF 优位 + 假阳/假阴清单）
// 注：tests.js 用单引号 JS 对象字面量风格（非 JSON 双引号）
const fs = require('fs');
let s = fs.readFileSync('data/tests.js', 'utf8');

const m = s.match(/标题: '假阳性与送检时机', 正文: '([^']+)'\s*\}/);
if (!m) { console.log('GM 锚点未找到'); process.exit(1); }
const gmOld = m[0];
const add = "\n      { 标题: '判读界值与标本（94书补充）', 正文: 'EORTC/MSG 2020 诊断标准建议：单次血清或血浆 GM≥1.0、或 BALF GM≥1.0、或血清 GM≥0.7 且 BALF GM≥0.8、脑脊液 GM≥1.0 可作为侵袭性曲霉病阳性诊断标准；不同试剂阳性界值有差异（一般 0.5），以试剂说明书为准。连续 2 次以上动态监测出现阳性的诊断提示意义更大。在非中性粒细胞减少患者中 BALF 样本的特异性和敏感性均优于血清。GM 释放量与曲霉菌负载量成正比，高水平可能预示较差预后、下降通常表示治疗有效。假阳性补充（94书）：交叉反应（荚膜组织胞浆菌、马尔尼菲篮状菌、青霉、拟青霉、隐球菌等）、食物中 GM 经受损肠黏膜入血、白蛋白/免疫球蛋白等营养液中的葡萄糖酸盐、多发性骨髓瘤高蛋白血症、纤维素透析膜、心肺旁路手术（大剂量肝素相关）、自身免疫性肝炎自身抗体干扰、新生儿与儿童（双歧杆菌交叉反应、肠黏膜屏障发育不完全）。假阴性：前带现象、释放入血的 GM 快速被清除、两性霉素 B 与三唑类抑制菌丝生长减少 GM 分泌、慢性肉芽肿等局部感染影响释放、菌丝血管侵袭弱入血少、非粒缺患者中性粒细胞吞噬清除。' }";
const gmNew = add + "\n    ],".replace('],', '],'); // 结构：新小节对象追加在数组内
// m[0] 形如 "正文: '...'}"，我们要在 } 前的数组末尾追加新对象
const gmNewFull = m[0] + ',' + add;
s = s.replace(gmOld, gmNewFull);
fs.writeFileSync('data/tests.js', s);
console.log('GM 试验补强完成');
